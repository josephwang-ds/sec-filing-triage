import { getTranslations } from "next-intl/server";
import type { DisclosureSignal } from "@/lib/contracts/snapshot";
import { count, percent } from "@/lib/format";

const TONES: Record<string, string> = {
  read_now: "bg-critical-soft text-critical border-critical/30",
  monitor: "bg-caution-soft text-caution border-caution/30",
  routine: "bg-positive-soft text-positive border-positive/30",
};

/**
 * The latest filing measured against this issuer's own filing history.
 *
 * Everything here is issuer-relative -- a percentile against this company's
 * past, never a rank against other companies -- and it describes reaction
 * *magnitude*, which carries no direction. The card is absent, not empty, when
 * the scoring run has not happened.
 */
export async function DisclosureSignalCard({
  signal,
}: {
  signal: DisclosureSignal | null | undefined;
}) {
  const t = await getTranslations("signal");
  if (!signal) return null;

  const tone = TONES[signal.state] ?? "bg-panel-muted text-muted border-line";
  const probability = percent(signal.probability, 0);
  const base = percent(signal.issuer_base_rate, 0);
  const history = count(signal.eligible_history);
  const model = signal.model;

  return (
    <section id="signal" className="scroll-mt-24 border-t border-line py-10 md:py-12">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between sm:gap-6">
        <div className="min-w-0">
          <p className="lens-eyebrow m-0 mb-2">{t("eyebrow")}</p>
          <h2 className="lens-serif m-0 text-2xl text-balance md:text-3xl">{t("title")}</h2>
        </div>
        <span
          className={`shrink-0 rounded-full border px-2.5 py-1 text-[11px] font-extrabold tracking-wide uppercase ${tone}`}
        >
          {t(`state.${signal.state}` as "state.read_now")}
        </span>
      </div>
      <p className="mt-3 mb-0 max-w-[70ch] text-sm text-muted">{t("intro")}</p>

      {probability ? (
        <dl className="lens-grid mt-6 grid grid-cols-1 gap-3 sm:grid-cols-3">
          {[
            { key: "probability", value: probability, label: t("probability") },
            { key: "base", value: base, label: t("base") },
            { key: "history", value: history, label: t("history") },
          ].map((row) => (
            <div
              key={row.key}
              className="flex min-w-0 flex-col gap-1 rounded-card border border-line bg-panel-muted p-4"
            >
              <dd className="lens-figure m-0 text-2xl break-words">{row.value}</dd>
              <dt className="text-[11px] text-muted">{row.label}</dt>
            </div>
          ))}
        </dl>
      ) : null}

      {signal.reasons.length ? (
        <div className="mt-5">
          <h3 className="m-0 mb-2 text-xs font-bold tracking-wide text-muted uppercase">
            {t("why")}
          </h3>
          <ul className="m-0 flex list-disc flex-col gap-1 pl-5 text-sm">
            {signal.reasons.map((reason) => (
              // Reasons are generated by the scorer in English and are left as
              // written: translating a generated explanation would make its
              // wording unverifiable against the run that produced it.
              <li key={reason} lang="en" className="break-words">
                {reason}
              </li>
            ))}
          </ul>
        </div>
      ) : null}

      <p className="mt-4 mb-0 border-l-[3px] border-accent bg-panel-muted px-4 py-3 text-xs text-muted">
        {t("boundary")}
      </p>

      {model ? (
        <p className="mt-3 mb-0 text-[11px] text-muted">
          {t("model", {
            estimator: model.estimator ?? "model",
            calibration: model.calibration ?? "n/a",
            through: model.evaluated_through ?? "n/a",
          })}
        </p>
      ) : null}
    </section>
  );
}
