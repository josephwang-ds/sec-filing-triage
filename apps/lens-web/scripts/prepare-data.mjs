#!/usr/bin/env node
/**
 * Stage the Python engine's output where the front end can read it.
 *
 * The research engine owns every number on this site. It writes one JSON
 * snapshot per issuer into `data/build/company_pages/`, and this script copies
 * those into `.lens/` before a dev server or a build starts. Nothing is
 * transformed on the way: a copy that edited a value would be a second place
 * for the numbers to be wrong.
 *
 * When no engine output exists -- a fresh clone, or CI without a data cache --
 * the committed fixtures under `fixtures/snapshots/` are staged instead and the
 * manifest records `source: "fixtures"`. The pages then show a visible
 * development banner. Fixture issuers are named SYNxxx and are generated by
 * `filing_triage.synth`; they are not market data and must never be presented
 * as any.
 */
import fs from "node:fs";
import path from "node:path";

const appRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const repoRoot = path.resolve(appRoot, "..", "..");
const stage = path.join(appRoot, ".lens");

// Real-data verification and release builds must fail closed. A missing runner
// cache must never silently turn a production build into a synthetic demo.
const requireEngine = /^(1|true|yes)$/i.test(process.env.LENS_REQUIRE_ENGINE ?? "");
const requiredTickers = (process.env.LENS_REQUIRED_TICKERS ?? "")
  .split(/[,\s]+/)
  .map((ticker) => ticker.trim().toUpperCase())
  .filter(Boolean);

function assertRequiredTickers(tickers, source) {
  const present = new Set(tickers.map((ticker) => String(ticker).toUpperCase()));
  const missing = requiredTickers.filter((ticker) => !present.has(ticker));
  if (missing.length) {
    console.error(
      `lens-web data: missing required real-company snapshots: ${missing.join(", ")} (${source})`,
    );
    process.exit(1);
  }
}


const snapshotDir = process.env.LENS_SNAPSHOT_DIR
  ? path.resolve(process.env.LENS_SNAPSHOT_DIR)
  : path.join(repoRoot, "data", "build", "company_pages");
const askFunction = path.join(repoRoot, "ops", "vercel", "ask", "index.js");
// Written by `scripts/export_ask_evidence.py`, which calls the same
// `build_ask_evidence` the production bundler calls. The packaged bundle's copy
// is the fallback, so a checkout that has run `make vercel-bundle` also works.
const askEvidenceCandidates = (
  process.env.LENS_ASK_EVIDENCE
    ? [path.resolve(process.env.LENS_ASK_EVIDENCE)]
    : [
        path.join(repoRoot, "data", "build", "ask-evidence.json"),
        path.join(
          repoRoot,
          "data",
          "build",
          "vercel_frontend",
          ".vercel",
          "output",
          "functions",
          "api",
          "ask.func",
          "evidence.json",
        ),
      ]
).filter((candidate) => fs.existsSync(candidate));
const askEvidence = askEvidenceCandidates[0];

/** A snapshot, as opposed to the other JSON the builder leaves in that folder. */
function isSnapshot(file) {
  try {
    const parsed = JSON.parse(fs.readFileSync(file, "utf8"));
    return Boolean(
      parsed &&
        typeof parsed === "object" &&
        parsed.ticker &&
        parsed.profile &&
        parsed.performance &&
        parsed.benchmark,
    );
  } catch {
    return false;
  }
}

function collect(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .map((name) => path.join(dir, name))
    .filter(isSnapshot)
    .sort();
}

function reset(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
}

// LENS_USE_FIXTURES is how a developer or a test run asks for the fixtures even
// when engine output is present: the fixtures are the only data that exercises
// every optional section and every absence at once.
const forced = /^(1|true|yes)$/i.test(process.env.LENS_USE_FIXTURES ?? "");
// A deployment whose build runs outside the repository -- the preview, which
// uploads only this app -- cannot reach the engine output or the evidence
// package. For that case the directory is staged here first and uploaded with
// the app, and LENS_USE_STAGED tells this script to keep what it finds rather
// than rebuilding it from paths that do not exist there.
if (/^(1|true|yes)$/i.test(process.env.LENS_USE_STAGED ?? "")) {
  const existing = path.join(stage, "manifest.json");
  if (fs.existsSync(existing)) {
    const staged = JSON.parse(fs.readFileSync(existing, "utf8"));
    if (requireEngine && staged.source !== "engine") {
      console.error("lens-web data: LENS_REQUIRE_ENGINE=1 refuses staged fixtures.");
      process.exit(1);
    }
    assertRequiredTickers(staged.tickers ?? [], "staged manifest");
    console.log(
      `lens-web data: using the staged directory as uploaded` +
        ` (${staged.tickers?.length ?? 0} snapshot(s) from ${staged.source};` +
        ` ask evidence ${staged.ask?.available ? "staged" : "unavailable"};` +
        ` research evidence ${staged.evidence?.length ?? 0} file(s))`,
    );
    process.exit(0);
  }
  console.error(`LENS_USE_STAGED is set but ${existing} does not exist.`);
  process.exit(1);
}

const engineSnapshots = forced ? [] : collect(snapshotDir);
const fixtureSnapshots = collect(path.join(appRoot, "fixtures", "snapshots"));
const useFixtures = engineSnapshots.length === 0;
const chosen = useFixtures ? fixtureSnapshots : engineSnapshots;

if (requireEngine && useFixtures) {
  console.error(
    `lens-web data: LENS_REQUIRE_ENGINE=1 but no engine snapshots were found at ${snapshotDir}. Refusing synthetic fixtures.`,
  );
  process.exit(1);
}
assertRequiredTickers(
  chosen.map((file) => JSON.parse(fs.readFileSync(file, "utf8")).ticker),
  useFixtures ? "fixtures" : "engine",
);

if (chosen.length === 0) {
  console.error(
    `No snapshots found.\n` +
      `  engine output: ${snapshotDir} (empty or absent)\n` +
      `  fixtures:      ${path.join(appRoot, "fixtures", "snapshots")} (empty or absent)\n\n` +
      `Build the engine's pages first:\n` +
      `  make company-pages\n` +
      `or point LENS_SNAPSHOT_DIR at a directory that holds them.`,
  );
  process.exit(1);
}

reset(stage);
const snapshotStage = path.join(stage, "snapshots");
fs.mkdirSync(snapshotStage, { recursive: true });
const tickers = [];
for (const file of chosen) {
  const parsed = JSON.parse(fs.readFileSync(file, "utf8"));
  const ticker = String(parsed.ticker).toUpperCase();
  tickers.push(ticker);
  fs.copyFileSync(file, path.join(snapshotStage, `${ticker.toLowerCase()}.json`));
}

// The Ask endpoint. The handler is the production function, copied rather than
// reimplemented, so the validation, budget and provider rules on the preview
// are the same code as the ones on the live site. Without an evidence bundle
// the route reports that Ask is unconfigured; it never answers unevidenced.
let ask = { available: false, reason: "evidence_missing" };
if (fs.existsSync(askFunction) && askEvidence) {
  const askStage = path.join(stage, "ask");
  fs.mkdirSync(askStage, { recursive: true });
  fs.copyFileSync(askFunction, path.join(askStage, "index.cjs"));
  fs.copyFileSync(askEvidence, path.join(askStage, "evidence.json"));
  ask = { available: true, reason: null };
} else if (!fs.existsSync(askFunction)) {
  ask = { available: false, reason: "handler_missing" };
}

// The research evidence package. The overview and research pages read their
// numbers out of these files, the same ones the Python pages read, so neither
// page can state a figure the evidence does not contain.
const evidenceSource = path.join(repoRoot, "evidence", "real_run");
const evidenceWanted = [
  "metrics.json",
  "manifest.json",
  "self_relative_metrics.json",
  "volatility_metrics.json",
  "calibration_metrics.json",
  "insider_metrics.json",
  "leakage_study.csv",
  "model_comparison.csv",
  "nlp_feature_ablation.csv",
  "self_relative_ablation.csv",
  "volatility_forecasters.csv",
  "recommendation_confusion.csv",
  "fold_metrics.csv",
];
const evidenceStage = path.join(stage, "research");
fs.mkdirSync(evidenceStage, { recursive: true });
const evidenceStaged = [];
for (const name of evidenceWanted) {
  const file = path.join(evidenceSource, name);
  if (!fs.existsSync(file)) continue;
  fs.copyFileSync(file, path.join(evidenceStage, name));
  evidenceStaged.push(name);
}

const manifest = {
  source: useFixtures ? "fixtures" : "engine",
  snapshot_dir: useFixtures ? "fixtures/snapshots" : snapshotDir,
  generated_at: new Date().toISOString(),
  tickers: tickers.sort(),
  ask,
  evidence: evidenceStaged,
};
fs.writeFileSync(path.join(stage, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

console.log(
  `lens-web data: ${tickers.length} snapshot(s) from ${manifest.source}` +
    ` (${manifest.snapshot_dir}); ask evidence ${ask.available ? "staged" : `unavailable (${ask.reason})`}` +
    `; research evidence ${evidenceStaged.length} file(s)`,
);
